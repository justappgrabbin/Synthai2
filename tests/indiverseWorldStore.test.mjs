import test from "node:test";
import assert from "node:assert/strict";
import { parseSavedWorlds, WORLD_LIBRARY_KEY } from "../client/src/lib/indiverseWorldStore.ts";

const createdByExistingUniverseCreator = {
  id: "1234567890",
  name: "Original Saved Universe",
  prompt: "A world generated by the existing universe creator",
  createdAt: "2026-11-03T10:00:00.000Z",
  seed: "abc12",
  layers: [{
    id: 1, name: "Physical / Substrate", function: "Environment",
    extractedData: "landscape"
  }]
};

test("reads existing SemanticUniverseCreator storage without renaming or rewriting it", () => {
  assert.equal(WORLD_LIBRARY_KEY, "semantic_universes");
  const parsed = parseSavedWorlds(JSON.stringify([createdByExistingUniverseCreator]));
  assert.deepEqual(parsed, [createdByExistingUniverseCreator]);
});
test("does not introduce invented worlds into an empty or corrupted library", () => {
  assert.deepEqual(parseSavedWorlds(null), []);
  assert.deepEqual(parseSavedWorlds("{broken"), []);
  assert.deepEqual(parseSavedWorlds(JSON.stringify({ world: "invalid" })), []);
});
test("preserves valid source entries and drops corrupt ones without mutating originals", () => {
  const source = [createdByExistingUniverseCreator, { id: "bad", name: "Incomplete" }];
  const before = JSON.stringify(source);
  assert.deepEqual(parseSavedWorlds(before), [createdByExistingUniverseCreator]);
  assert.equal(JSON.stringify(source), before);
});
